/**
 * Generates public/robots.txt and public/sitemap.xml from site.config.ts and
 * nav-links.ts so a rebrand never requires hand-editing XML.
 * Runs automatically as `prebuild` (Node 24 strips TS types natively).
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { siteConfig } = await import(path.join(root, 'src/app/config/site.config.ts'));
const { NAV_LINKS } = await import(path.join(root, 'src/app/shared/nav-links.ts'));

const siteUrl = siteConfig.siteUrl.replace(/\/+$/, '');
const today = new Date().toISOString().slice(0, 10);

const urls = NAV_LINKS.map(({ path: p }) => {
  const loc = p === '/' ? `${siteUrl}/` : `${siteUrl}${p}`;
  const priority = p === '/' ? '1.0' : p === '/decor' || p === '/services' ? '0.9' : '0.7';
  return `  <url>\n    <loc>${loc}</loc>\n    <lastmod>${today}</lastmod>\n    <changefreq>monthly</changefreq>\n    <priority>${priority}</priority>\n  </url>`;
});

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by scripts/generate-seo-files.mjs from site.config.ts — do not edit by hand. -->\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join('\n')}\n</urlset>\n`;

const robots = `# Generated by scripts/generate-seo-files.mjs from site.config.ts — do not edit by hand.\nUser-agent: *\nAllow: /\nDisallow: /404\n\nSitemap: ${siteUrl}/sitemap.xml\n`;

await mkdir(path.join(root, 'public'), { recursive: true });
await writeFile(path.join(root, 'public/sitemap.xml'), sitemap);
await writeFile(path.join(root, 'public/robots.txt'), robots);
console.log(`[seo] wrote public/sitemap.xml (${NAV_LINKS.length} urls) and public/robots.txt for ${siteUrl}`);
